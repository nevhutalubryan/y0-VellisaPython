# Write a function `half` that accepts a number as an argument.
# The function should return half of the number.

def half(number):
    return number / 2

print(half(10))  # Should print 5.0
print(half(15))  # Should print 7.5
print(half(20))  # Should print 10.0
print(half(4))
print(half(2))
print(half(6))   